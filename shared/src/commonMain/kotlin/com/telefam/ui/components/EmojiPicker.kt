/**
 * Full emoji picker panel shown above the input bar. Tapping an emoji inserts it into
 * the message draft. Pure content UI — no decoration.
 */
@Composable
fun EmojiPickerPanel(onPick: (String) -> Unit, modifier: Modifier = Modifier) {
    var categoryIndex by remember { mutableIntStateOf(0) }
    Column(modifier.fillMaxWidth().height(300.dp).background(MaterialTheme.colorScheme.surface)) {
        Row(
            Modifier.fillMaxWidth().padding(horizontal = 8.dp, vertical = 6.dp),
            horizontalArrangement = Arrangement.spacedBy(4.dp)
        ) {
            EmojiData.categories.forEachIndexed { i, (name, emojis) ->
                val selected = i == categoryIndex
                Text(
                    emojis.first(), fontSize = 18.sp,
                    modifier = Modifier
                        .clip(RoundedCornerShape(10.dp))
                        .background(if (selected) MaterialTheme.colorScheme.surfaceVariant else MaterialTheme.colorScheme.surface)
                        .clickable { categoryIndex = i }
                        .padding(horizontal = 8.dp, vertical = 6.dp)
                )
            }
        }
        val emojis = EmojiData.categories[categoryIndex].second
        LazyVerticalGrid(
            columns = GridCells.Fixed(8),
            modifier = Modifier.fillMaxSize().padding(horizontal = 6.dp)
        ) {
            items(emojis) { emoji ->
                Box(
                    Modifier.aspectRatio(1f).clip(RoundedCornerShape(8.dp))
                        .clickable { onPick(emoji) },
                    contentAlignment = Alignment.Center
                ) {
                    Text(emoji, fontSize = 22.sp)
                }
            }
        }
    }
}
